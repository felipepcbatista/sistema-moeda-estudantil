-- Schema inicial do Sistema de Moeda Estudantil (Lab03S02).
-- Espelha o diagrama de classes e o modelo ER (docs/diagramas/modelo-er.puml).
-- Heranca de Usuario: JOINED (uma tabela por subclasse, PK = FK para usuario).
-- Heranca de Transacao: SINGLE_TABLE (uma tabela, coluna discriminadora "tipo").

CREATE TABLE instituicao_ensino (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE conta (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saldo INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_conta_saldo_nao_negativo CHECK (saldo >= 0)
);

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login      VARCHAR(60)  NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL
);

CREATE TABLE aluno (
    id             BIGINT       NOT NULL PRIMARY KEY REFERENCES usuario (id),
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    cpf            VARCHAR(11)  NOT NULL UNIQUE,
    rg             VARCHAR(20)  NOT NULL,
    curso          VARCHAR(100) NOT NULL,
    logradouro     VARCHAR(150) NOT NULL,
    numero         VARCHAR(10)  NOT NULL,
    complemento    VARCHAR(60),
    bairro         VARCHAR(80)  NOT NULL,
    cidade         VARCHAR(80)  NOT NULL,
    uf             VARCHAR(2)   NOT NULL,
    cep            VARCHAR(8)   NOT NULL,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao_ensino (id),
    conta_id       BIGINT       NOT NULL UNIQUE REFERENCES conta (id)
);

CREATE TABLE professor (
    id             BIGINT       NOT NULL PRIMARY KEY REFERENCES usuario (id),
    nome           VARCHAR(150) NOT NULL,
    cpf            VARCHAR(11)  NOT NULL UNIQUE,
    departamento   VARCHAR(100) NOT NULL,
    instituicao_id BIGINT       NOT NULL REFERENCES instituicao_ensino (id),
    conta_id       BIGINT       NOT NULL UNIQUE REFERENCES conta (id)
);

CREATE TABLE empresa_parceira (
    id            BIGINT       NOT NULL PRIMARY KEY REFERENCES usuario (id),
    nome_fantasia VARCHAR(150) NOT NULL,
    cnpj          VARCHAR(14)  NOT NULL UNIQUE,
    email         VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE vantagem (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(120) NOT NULL,
    descricao    VARCHAR(500) NOT NULL,
    foto_url     VARCHAR(300) NOT NULL,
    custo_moedas INTEGER      NOT NULL,
    ativa        BOOLEAN      NOT NULL DEFAULT TRUE,
    empresa_id   BIGINT       NOT NULL REFERENCES empresa_parceira (id),
    CONSTRAINT ck_vantagem_custo_positivo CHECK (custo_moedas > 0)
);

CREATE TABLE transacao (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo             VARCHAR(20) NOT NULL,
    valor            INTEGER     NOT NULL,
    data_hora        TIMESTAMP   NOT NULL,
    conta_origem_id  BIGINT REFERENCES conta (id),
    conta_destino_id BIGINT REFERENCES conta (id),
    motivo           VARCHAR(500),
    codigo           VARCHAR(20) UNIQUE,
    semestre         VARCHAR(7),
    vantagem_id      BIGINT REFERENCES vantagem (id),
    CONSTRAINT ck_transacao_valor_positivo CHECK (valor > 0),
    CONSTRAINT ck_transacao_tipo CHECK (tipo IN ('ENVIO', 'RESGATE', 'CREDITO'))
);

CREATE INDEX ix_transacao_conta_origem ON transacao (conta_origem_id);
CREATE INDEX ix_transacao_conta_destino ON transacao (conta_destino_id);
CREATE INDEX ix_vantagem_empresa ON vantagem (empresa_id);
